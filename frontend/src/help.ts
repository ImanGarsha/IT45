/**
 * The in-app manual: one plain-English sentence or two for every label in IT45.
 *
 * The HelpLayer finds what you hover and looks its visible label up here (menu item, heading,
 * button, form field, stat tile, column header; a table cell uses its column's header).
 * Elements with a specific `data-help` attribute override this. Keys are normalised by
 * `helpKey`: lower case, digits replaced by "#", sort arrows and extra spaces removed.
 * scripts/help_audit.mjs walks every page and lists any visible label missing from here.
 */
export function helpKey(s: string): string {
  return s.replace(/[▲▼]/g, "").replace(/\s+/g, " ").trim().toLowerCase().replace(/\d+(\.\d+)?/g, "#");
}

